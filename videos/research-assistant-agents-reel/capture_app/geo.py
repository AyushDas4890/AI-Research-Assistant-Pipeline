"""assets/cap/geometry.json → film/geo.js (window.GEO). Run from the project root after capture_app/measure.mjs.

Range.getClientRects() returns the element boxes as well as one rect per text line, so line lists are
deduplicated by y, keeping the widest rect on each row.
"""
import json

geo = json.load(open("assets/cap/geometry.json"))


def dedupe(rects):
    rows = {}
    for r in rects:
        key = round(r["y"])
        if key not in rows or r["w"] > rows[key]["w"]:
            rows[key] = r
    return [rows[k] for k in sorted(rows)]


for state in geo.values():
    for key in ("logLines", "sideLines"):
        if key in state:
            state[key] = dedupe(state[key])

with open("film/geo.js", "w") as f:
    f.write("// GENERATED by capture_app/geo.py from assets/cap/geometry.json (CSS px of the 1600x1000 capture). Never edit.\n")
    f.write("window.GEO = " + json.dumps(geo, separators=(",", ":")) + ";\n")
print({k: (len(v.get("logLines", [])), len(v.get("sideLines", []))) for k, v in geo.items()})
